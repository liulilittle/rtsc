def sha16(p):
    if not os.path.exists(p):
        return '<absent>'
    h = hashlib.sha256()
    with open(p, 'rb') as f:
        for c in iter(lambda: f.read(1 << 16), b''):
            h.update(c)
    return h.hexdigest()[:16]


def lines(p):
    if not os.path.exists(p):
        return 0
    return len(io.open(p, encoding='utf-8', errors='replace').read().splitlines())


